// Apply i18n to all elements with data-i18n attribute
function applyI18n(lang) {
  var t = I18N[lang] || I18N.nl;
  var els = document.querySelectorAll('[data-i18n]');
  els.forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.textContent = t[key];
    }
  });
  // Also update placeholder attributes
  var placeholderEls = document.querySelectorAll('[data-i18n-placeholder]');
  placeholderEls.forEach(function(el) {
    var key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) {
      el.placeholder = t[key];
    }
  });
}

function getLang() {
  return localStorage.getItem('lang') || 'nl';
}

function setLang(lang) {
  localStorage.setItem('lang', lang);
  applyI18n(lang);
  // Update toggle button
  var btn = document.getElementById('lang-toggle');
  if (btn) {
    btn.textContent = I18N[lang].nav_language;
  }
}

function t(key) {
  var lang = getLang();
  var strings = I18N[lang] || I18N.nl;
  return strings[key] !== undefined ? strings[key] : key;
}

// Format date to Dutch or English
function formatDate(dateStr, lang) {
  var months_nl = ['januari','februari','maart','april','mei','juni','juli','augustus','september','oktober','november','december'];
  var months_en = ['January','February','March','April','May','June','July','August','September','October','November','December'];
  var d = new Date(dateStr);
  var day = d.getDate();
  var month = lang === 'en' ? months_en[d.getMonth()] : months_nl[d.getMonth()];
  var year = d.getFullYear();
  if (lang === 'en') return month + ' ' + day + ', ' + year;
  return day + ' ' + month + ' ' + year;
}
